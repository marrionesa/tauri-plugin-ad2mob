#!/usr/bin/env node
/**
 * Cross-language contract verification for `tauri-plugin-ad2mob`.
 *
 * This is the single source of truth for "do all four implementations agree?".
 * It parses the actual source files (no imports, no compilation) and asserts
 * that the contract — commands, permissions, events and error codes — is
 * identical across the Rust core, the Android (Kotlin) implementation, the
 * iOS (Swift) implementation and the TypeScript guest bindings, and that the
 * published docs (README) and the release metadata (CHANGELOG + versions)
 * are in sync.
 *
 * Exits with code 0 when every check passes, 1 otherwise.
 *
 * Usage:  node scripts/check-contract.mjs   (run from anywhere)
 */

import { readFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// ---------------------------------------------------------------------------
// Tiny check runner
// ---------------------------------------------------------------------------

let passed = 0
let failed = 0
const failures = []

/** @param {string} label @param {() => string | true} fn error message or true */
function check(label, fn) {
  try {
    const result = fn()
    if (result === true) {
      passed++
      console.log(`  \x1b[32m✔\x1b[0m ${label}`)
    } else {
      failed++
      failures.push([label, result])
      console.log(`  \x1b[31m✘ ${label}\x1b[0m`)
    }
  } catch (error) {
    failed++
    failures.push([label, error instanceof Error ? error.message : String(error)])
    console.log(`  \x1b[31m✘ ${label}\x1b[0m`)
  }
}

function fail(message) {
  throw new Error(message)
}

/** Asserts two string arrays are the same set. Returns error text or true. */
function sameSet(label, actual, expected) {
  const a = [...new Set(actual)].sort()
  const e = [...new Set(expected)].sort()
  const missing = e.filter((x) => !a.includes(x))
  const extra = a.filter((x) => !e.includes(x))
  if (missing.length === 0 && extra.length === 0) return true
  const parts = []
  if (missing.length) parts.push(`missing from ${label}: ${missing.join(', ')}`)
  if (extra.length) parts.push(`unexpected in ${label}: ${extra.join(', ')}`)
  return parts.join(' — ')
}

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8')
const uniq = (list) => [...new Set(list)]

// ---------------------------------------------------------------------------
// Extraction helpers (regexes tuned to the actual source formatting)
// ---------------------------------------------------------------------------

/** snake_case → camelCase */
function toCamel(snake) {
  return snake.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase())
}
/** snake_case → kebab-case */
function toKebab(snake) {
  return snake.replace(/_/g, '-')
}

/** Commands registered for the ACL in build.rs (the canonical surface). */
function extractBuildRsCommands() {
  const src = read('build.rs')
  const block = src.match(/const COMMANDS:\s*&\[&str\]\s*=\s*&\[(.*?)\];/s)
  if (!block) fail('build.rs: COMMANDS block not found')
  return uniq([...block[1].matchAll(/"([a-z_]+)"/g)].map((m) => m[1]))
}

/** Commands registered in the Tauri invoke handler (lib.rs). */
function extractRustCommands() {
  const src = read('src/lib.rs')
  const block = src.match(/generate_handler!\[(.*?)\]/s)
  if (!block) fail('src/lib.rs: generate_handler! block not found')
  return uniq([...block[1].matchAll(/commands::([a-z_]+)/g)].map((m) => m[1]))
}

/** Commands forwarded to the native layer (mobile.rs plugin-handle methods). */
function extractNativeForwardedCommands() {
  const src = read('src/mobile.rs')
  return uniq([...src.matchAll(/pub async fn ([a-z_]+)\(/g)].map((m) => m[1]))
}

/** @Command methods in the Kotlin plugin. */
function extractKotlinCommands() {
  const src = read('android/src/main/java/com/plugin/admob/AdmobPlugin.kt')
  const names = uniq([...src.matchAll(/@Command\s+(?:\n\s*)?fun\s+(\w+)\(/g)].map((m) => m[1]))
  return names.map(toCamel)
}

/** @objc public command methods in the Swift plugin. */
function extractSwiftCommands() {
  const src = read('ios/Sources/AdmobPlugin.swift')
  return uniq([...src.matchAll(/@objc\s+public\s+func\s+(\w+)\(/g)].map((m) => toCamel(m[1])))
}

/** Commands invoked by the TypeScript guest bindings. */
function extractTsCommands() {
  const src = read('guest-js/index.ts')
  return uniq([...src.matchAll(/call<[^>]*>\(\s*'([a-z_]+)'/g)].map((m) => m[1]))
}

/** Permission .toml files autogenerated by the ACL build. */
function extractAutogeneratedPermissions() {
  const dir = join(ROOT, 'permissions', 'autogenerated', 'commands')
  if (!existsSync(dir)) fail('permissions/autogenerated/commands: directory missing')
  return readdirSync(dir)
    .filter((f) => f.endsWith('.toml'))
    .map((f) => f.replace(/^allow-/, '').replace(/\.toml$/, ''))
    .map((kebab) => kebab.replace(/-/g, '_'))
}

/** allow-* identifiers granted by the default permission set. */
function extractDefaultPermissions() {
  const src = read('permissions/default.toml')
  if (!src.includes('schemas/schema.json')) fail('permissions/default.toml: missing $schema line')
  return uniq([...src.matchAll(/"(allow-[a-z-]+)"/g)].map((m) => m[1].replace('allow-', '').replace(/-/g, '_')))
}

/** Event names declared in each implementation (all `admob://*`). */
function extractEvents() {
  const rust = uniq([...read('src/models.rs').matchAll(/pub const \w+: &str = "(admob:\/\/[^"]+)"/g)].map((m) => m[1]))
  const kotlin = uniq(
    [...read('android/src/main/java/com/plugin/admob/AdmobEvents.kt').matchAll(/const val \w+ = "(admob:\/\/[^"]+)"/g)].map(
      (m) => m[1],
    ),
  )
  const swift = uniq(
    [...read('ios/Sources/AdmobEvents.swift').matchAll(/static let \w+ = "(admob:\/\/[^"]+)"/g)].map((m) => m[1]),
  )
  const ts = uniq([...read('guest-js/types.ts').matchAll(/'(admob:\/\/[^']+)':/g)].map((m) => m[1]))
  return { rust, kotlin, swift, ts }
}

/** Error codes mapped by the Rust core (`Error::code()`). */
function extractRustErrorCodes() {
  const src = read('src/error.rs')
  const codes = uniq([...src.matchAll(/Error::\w+(?:\([^)]*\))?\s*=>\s*"([A-Z_]+)"/g)].map((m) => m[1]))
  if (codes.length === 0) fail('src/error.rs: no error-code mapping found')
  return codes
}

/** Error codes declared in the TypeScript guest bindings. */
function extractTsErrorCodes() {
  const src = read('guest-js/errors.ts')
  const block = src.match(/export type AdMobErrorCode =([\s\S]*?)\n\}/)
  if (!block) fail('guest-js/errors.ts: AdMobErrorCode union not found')
  return uniq([...block[1].matchAll(/'([A-Z_]+)'/g)].map((m) => m[1]))
}

/** Error codes declared by the Kotlin reject-code table. */
function extractKotlinErrorCodes() {
  const src = read('android/src/main/java/com/plugin/admob/AdmobMappers.kt')
  const block = src.match(/object AdmobRejectCodes\s*\{(.*?)\n\}/s)
  if (!block) fail('AdmobMappers.kt: object AdmobRejectCodes not found')
  return uniq([...block[1].matchAll(/const val \w+ = "([A-Z_]+)"/g)].map((m) => m[1]))
}

/** Error codes used inline by the Swift implementation (subset check). */
function extractSwiftUsedErrorCodes() {
  const codes = []
  for (const file of readdirSync(join(ROOT, 'ios', 'Sources'))) {
    if (!file.endsWith('.swift')) continue
    const src = read(join('ios', 'Sources', file))
    codes.push(...[...src.matchAll(/code:\s*"([A-Z_]+)"/g)].map((m) => m[1]))
  }
  return uniq(codes)
}

/** Version of the crate from Cargo.toml. */
function cargoVersion() {
  const m = read('Cargo.toml').match(/^version\s*=\s*"([^"]+)"/m)
  if (!m) fail('Cargo.toml: version not found')
  return m[1]
}

/** Version of the npm package from package.json. */
function npmVersion() {
  return JSON.parse(read('package.json')).version
}

/** Latest released version from CHANGELOG.md (first non-Unreleased heading). */
function changelogVersion() {
  const m = read('CHANGELOG.md').match(/##\s*\[(\d+\.\d+\.\d+)\]/)
  if (!m) fail('CHANGELOG.md: no released version heading found')
  return m[1]
}

// ---------------------------------------------------------------------------
// Suites
// ---------------------------------------------------------------------------

const canonical = extractBuildRsCommands()
const rustCommands = extractRustCommands()
const nativeForwarded = extractNativeForwardedCommands()
const kotlinCommands = extractKotlinCommands()
const swiftCommands = extractSwiftCommands()
const tsCommands = extractTsCommands()
const autogenerated = extractAutogeneratedPermissions()
const defaultPerms = extractDefaultPermissions()

/** Framework commands provided by the Tauri `Plugin` base classes. */
const BASE_COMMANDS = ['register_listener', 'remove_listener']
/** Commands answered purely by the Rust core (never forwarded to native). */
const RUST_ONLY_COMMANDS = [
  'configure',
  'is_supported',
  'get_status',
  'get_consent_status',
  'get_tracking_authorization_status',
  'is_interstitial_ready',
  'is_rewarded_ready',
  'is_banner_visible',
]

console.log('\n\x1b[1m  tauri-plugin-ad2mob · contract verification\x1b[0m\n')

console.log('\x1b[1mCommands\x1b[0m')
check(
  `build.rs COMMANDS declares the canonical surface (${canonical.length} commands, incl. ${BASE_COMMANDS.length} base listener commands)`,
  () => (canonical.length >= 20 ? true : `only ${canonical.length} commands found`),
)
check(
  'lib.rs generate_handler! registers every canonical command except the base listener commands',
  () => sameSet('generate_handler!', rustCommands, canonical.filter((c) => !BASE_COMMANDS.includes(c))),
)
check(
  'Rust-only commands are exactly the documented set (answered by the core, never native)',
  () => sameSet('rust-only commands', rustCommands.filter((c) => !nativeForwarded.includes(c)), RUST_ONLY_COMMANDS),
)
check(
  'mobile.rs forwards exactly the commands that are not Rust-only',
  () => sameSet('mobile.rs', nativeForwarded, rustCommands.filter((c) => !RUST_ONLY_COMMANDS.includes(c))),
)
check(`Kotlin @Command implements every native-forwarded command (${kotlinCommands.length})`, () =>
  sameSet('Kotlin @Command', kotlinCommands, nativeForwarded.map(toCamel)),
)
check(`Swift @objc implements every native-forwarded command (${swiftCommands.length})`, () =>
  sameSet('Swift @objc', swiftCommands, nativeForwarded.map(toCamel)),
)
check(`TypeScript bindings invoke every Rust command (${tsCommands.length})`, () =>
  sameSet('guest-js calls', tsCommands, rustCommands),
)
check('TypeScript invokes no command outside the canonical surface', () => {
  const unknown = tsCommands.filter((c) => !canonical.includes(c))
  return unknown.length === 0 ? true : `unknown commands: ${unknown.join(', ')}`
})

console.log('\n\x1b[1mPermissions (ACL)\x1b[0m')
check(`autogenerated permissions cover every canonical command (${autogenerated.length} files)`, () =>
  sameSet('autogenerated permissions', autogenerated, canonical),
)
check('permissions/default.toml grants every canonical command', () => sameSet('default.toml', defaultPerms, canonical))
check('permissions/schemas/schema.json exists', () =>
  existsSync(join(ROOT, 'permissions', 'schemas', 'schema.json')) ? true : 'file missing',
)
{
  const reference = existsSync(join(ROOT, 'permissions', 'autogenerated', 'reference.md'))
    ? read('permissions/autogenerated/reference.md')
    : ''
  check('autogenerated/reference.md documents every command', () => {
    if (!reference) return 'reference.md missing'
    const missing = canonical.filter((c) => !reference.includes(toKebab(c)))
    return missing.length === 0 ? true : `missing: ${missing.map(toKebab).join(', ')}`
  })
}

console.log('\n\x1b[1mEvents\x1b[0m')
const events = extractEvents()
check(`Rust declares the event catalog (${events.rust.length} events)`, () =>
  events.rust.length >= 20 ? true : `only ${events.rust.length} events`,
)
check('Kotlin event constants match the Rust catalog', () => sameSet('Kotlin events', events.kotlin, events.rust))
check('Swift event constants match the Rust catalog', () => sameSet('Swift events', events.swift, events.rust))
check('TypeScript AdMobEventMap matches the Rust catalog', () => sameSet('TS events', events.ts, events.rust))
check('README documents every event (full name or grouped shorthand)', () => {
  const readme = read('README.md')
  const missing = events.rust.filter((e) => {
    const name = e.replace('admob://', '')
    if (readme.includes(`admob://${name}`)) return false
    const shorthand = `\`-${name.split('-').slice(1).join('-')}\``
    return !readme.includes(shorthand)
  })
  return missing.length === 0 ? true : `missing: ${missing.join(', ')}`
})
check('guest-js event module compiles against AdMobEventMap', () =>
  existsSync(join(ROOT, 'guest-js', 'events.ts')) && read('guest-js/events.ts').includes('AdMobEventMap'),
)

console.log('\n\x1b[1mError codes\x1b[0m')
const rustCodes = extractRustErrorCodes()
const tsCodes = extractTsErrorCodes()
const kotlinCodes = extractKotlinErrorCodes()
const swiftUsed = extractSwiftUsedErrorCodes()
check(`Rust core maps every error to a stable code (${rustCodes.length} codes)`, () => (rustCodes.length >= 8 ? true : 'too few codes'))
check('TypeScript AdMobErrorCode matches the Rust catalog', () => sameSet('TS error codes', tsCodes, rustCodes))
check('Kotlin AdmobRejectCodes matches the Rust catalog', () => sameSet('Kotlin error codes', kotlinCodes, rustCodes))
check('Swift only rejects with codes from the catalog', () => {
  const unknown = swiftUsed.filter((c) => !rustCodes.includes(c))
  return unknown.length === 0 ? true : `unknown codes: ${unknown.join(', ')}`
})
check('README documents every error code', () => {
  const readme = read('README.md')
  const missing = rustCodes.filter((c) => !readme.includes(`\`${c}\``))
  return missing.length === 0 ? true : `missing: ${missing.join(', ')}`
})

console.log('\n\x1b[1mRelease metadata\x1b[0m')
check('versions agree (Cargo.toml, package.json, CHANGELOG)', () => {
  const cargo = cargoVersion()
  const npm = npmVersion()
  const changelog = changelogVersion()
  if (cargo === npm && npm === changelog) return true
  return `Cargo.toml=${cargo} package.json=${npm} CHANGELOG=${changelog}`
})
check('npm package name matches the crate name', () => {
  const pkg = JSON.parse(read('package.json'))
  return pkg.name === 'tauri-plugin-ad2mob' ? true : `unexpected npm name: ${pkg.name}`
})
check('README references the canonical repository (marrionesa/tauri-plugin-ad2mob)', () => {
  const readme = read('README.md')
  if (readme.includes('github.com/marrionesa/tauri-plugin-ad2mob')) return true
  return 'canonical repository URL not found'
})

// ---------------------------------------------------------------------------
// Result
// ---------------------------------------------------------------------------

console.log(`\n  \x1b[1mRESULT: ${passed} passed, ${failed} failed\x1b[0m`)
if (failed > 0) {
  console.log('\n  Failures:')
  for (const [label, reason] of failures) {
    console.log(`  \x1b[31m✘ ${label}\x1b[0m\n    ${reason}`)
  }
  console.log()
  process.exit(1)
}
console.log()
